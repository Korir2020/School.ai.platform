import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

function staticShellServiceWorker() {
  return {
    name: 'marian-static-shell-service-worker',
    generateBundle(_options, bundle) {
      const knownAssets = [
        '/', '/index.html', '/manifest.webmanifest', '/favicon.svg', '/apple-touch-icon.png',
        '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png',
        ...Object.keys(bundle).filter((name) => /^assets\/.*\.(?:js|mjs|css|svg|png|jpe?g|webp|ico|woff2?)$/i.test(name)).map((name) => `/${name}`),
      ];
      const worker = `/* Generated by Vite. Cache the public static shell only; all APIs and mutations are network-only. */
const CACHE = 'marian-shell-v1';
const ASSETS = ${JSON.stringify([...new Set(knownAssets)])};
const PRIVATE_PATH = /(?:^|\\/)(?:api|auth|receipt|receipts|report|reports|attachment|attachments|private|mutation)(?:\\/|$)/i;
function allowed(request, url) {
  if (request.method !== 'GET' || url.origin !== self.location.origin || request.headers.has('Authorization') || url.search || url.hash) return false;
  if (PRIVATE_PATH.test(url.pathname) || /^\\/api(?:\\/|$)/i.test(url.pathname)) return false;
  return ASSETS.includes(url.pathname);
}
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith('marian-shell-') && key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  let url;
  try { url = new URL(request.url); } catch { return; }
  if (!allowed(request, url)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(url.pathname);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response.ok && response.type === 'basic') await cache.put(url.pathname, response.clone());
      return response;
    } catch (error) {
      if (cached) return cached;
      throw error;
    }
  })());
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker });
    },
  }
}

export default defineConfig({
  plugins: [react(), staticShellServiceWorker()],
  server: { allowedHosts: ['.manus.computer'], proxy: { '/api': { target: process.env.VITE_API_TARGET || 'https://school-ai-platform.onrender.com', changeOrigin: true,
        configure: (p) => p.on('proxyReq', (r) => r.removeHeader('origin')) } } },
})
